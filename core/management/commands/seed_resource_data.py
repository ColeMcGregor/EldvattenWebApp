
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from accounts.models import AccountStatus, User
from organization.models import Chapter, CommunityGroup
from resources.models import Resource, ResourceTarget
from resources.storage import private_resource_storage


SEED_MARKER = "Generated by seed_resource_data. Development data only."
SEED_DIRECTORY = "resources/dev_samples"


class Command(BaseCommand):
    help = "Seed development Resources with files, links, and visibility rules."

    def handle(self, *args, **options):
        if not settings.DEBUG:
            raise CommandError(
                "seed_resource_data can only run when DEBUG is enabled."
            )

        try:
            owner = User.objects.get(username="suTest")
            member = User.objects.get(username="testuser01")
            excluded_member = User.objects.get(username="testuser02")
            chapter = Chapter.objects.get(name="Fyr Draca Chapter")
            group = CommunityGroup.objects.get(name="Test Custom Group")

        except (
            User.DoesNotExist,
            Chapter.DoesNotExist,
            CommunityGroup.DoesNotExist,
        ) as error:
            raise CommandError(
                "Required development users or groups are missing. "
                "Run seed_dev_data first."
            ) from error

        for user in (owner, member, excluded_member):
            if (
                not user.is_active
                or user.account_status != AccountStatus.MEMBER
            ):
                raise CommandError(
                    f"{user.username} must be an active member."
                )

        samples = [
            {
                "title": "[DEV] Member Handbook",
                "description": "General reference material for members.",
                "filename": "member_handbook.md",
                "content": (
                    "# EldVatten Member Handbook\n\n"
                    "Development sample. Not an official handbook.\n\n"
                    "## Community\n\n"
                    "EldVatten is a volunteer educational organization "
                    "focused on Viking-era history, research, and "
                    "reenactment.\n\n"
                    "## Participation\n\n"
                    "Members can participate in chapters, households, "
                    "Orders, and community groups.\n"
                ),
                "visibility": Resource.Visibility.MEMBERS,
                "sort_order": 10,
                "targets": [],
            },
            {
                "title": "[DEV] Event Planning Checklist",
                "description": "Example event preparation checklist.",
                "filename": "event_checklist.md",
                "content": (
                    "# Event Planning Checklist\n\n"
                    "- [ ] Define event goals\n"
                    "- [ ] Select a location\n"
                    "- [ ] Confirm organizers\n"
                    "- [ ] Prepare equipment\n"
                    "- [ ] Review safety requirements\n"
                    "- [ ] Confirm accessibility needs\n"
                    "- [ ] Announce the event\n"
                    "- [ ] Collect feedback\n"
                ),
                "visibility": Resource.Visibility.MEMBERS,
                "sort_order": 20,
                "targets": [
                    (
                        ResourceTarget.Effect.EXCLUDE,
                        {"user": excluded_member},
                    ),
                ],
            },
            {
                "title": "[DEV] Chapter Meeting Agenda",
                "description": "Example resource restricted to one chapter.",
                "filename": "chapter_agenda.md",
                "content": (
                    "# Chapter Meeting Agenda\n\n"
                    "Development sample.\n\n"
                    "1. Opening\n"
                    "2. Attendance\n"
                    "3. Previous business\n"
                    "4. Current business\n"
                    "5. Upcoming activities\n"
                    "6. Closing\n"
                ),
                "visibility": Resource.Visibility.CUSTOM,
                "sort_order": 30,
                "targets": [
                    (
                        ResourceTarget.Effect.INCLUDE,
                        {"chapter": chapter},
                    ),
                ],
            },
            {
                "title": "[DEV] Community Group Notes",
                "description": "Example resource restricted to a community group.",
                "filename": "group_notes.md",
                "content": (
                    "# Community Group Notes\n\n"
                    "Development sample.\n\n"
                    "## Discussion Topics\n\n"
                    "- Group activities\n"
                    "- Upcoming projects\n"
                    "- Equipment and materials\n"
                    "- Member participation\n"
                ),
                "visibility": Resource.Visibility.CUSTOM,
                "sort_order": 40,
                "targets": [
                    (
                        ResourceTarget.Effect.INCLUDE,
                        {"community_group": group},
                    ),
                ],
            },
            {
                "title": "[DEV] Budget Template",
                "description": "Example CSV accessible to one selected member.",
                "filename": "budget_template.csv",
                "content": (
                    "Category,Description,Estimated Cost,Actual Cost\n"
                    "Venue,Event location,0,0\n"
                    "Materials,Workshop supplies,0,0\n"
                    "Travel,Transportation,0,0\n"
                    "Other,Miscellaneous,0,0\n"
                ),
                "visibility": Resource.Visibility.CUSTOM,
                "sort_order": 50,
                "targets": [
                    (
                        ResourceTarget.Effect.INCLUDE,
                        {"user": member},
                    ),
                ],
            },
            {
                "title": "[DEV] Birka Historical Reference",
                "description": "External historical reference link.",
                "external_url": "https://en.wikipedia.org/wiki/Birka",
                "visibility": Resource.Visibility.MEMBERS,
                "sort_order": 60,
                "targets": [],
            },
            {
                "title": "[DEV] Archived Reference Link",
                "description": "Example inactive resource for management testing.",
                "external_url": "https://example.org/",
                "visibility": Resource.Visibility.MEMBERS,
                "sort_order": 70,
                "is_active": False,
                "targets": [],
            },
        ]

        with transaction.atomic():
            created_count = 0
            updated_count = 0

            for sample in samples:
                matches = list(
                    Resource.objects.select_for_update().filter(
                        title=sample["title"]
                    )
                )

                if len(matches) > 1:
                    raise CommandError(
                        f"Multiple Resources already have the title "
                        f"{sample['title']!r}. Resolve the duplicates first."
                    )

                if matches:
                    resource = matches[0]

                    if (
                        resource.created_by_id != owner.pk
                        or not resource.description.startswith(SEED_MARKER)
                    ):
                        raise CommandError(
                            f"Resource {sample['title']!r} already exists "
                            "but is not owned by this seeder."
                        )

                    updated_count += 1

                else:
                    resource = Resource(
                        created_by=owner,
                    )
                    created_count += 1

                resource.title = sample["title"]
                resource.description = (
                    f"{SEED_MARKER}\n\n"
                    f"{sample['description']}"
                )

                resource.visibility = sample["visibility"]
                resource.sort_order = sample["sort_order"]
                resource.is_active = sample.get("is_active", True)

                if "filename" in sample:
                    resource.resource_type = Resource.ResourceType.FILE
                    resource.external_url = ""

                    stored_name = (
                        f"{SEED_DIRECTORY}/{sample['filename']}"
                    )

                    resource.file.name = stored_name

                    self.write_sample_file(
                        stored_name,
                        sample["content"],
                    )

                else:
                    resource.resource_type = Resource.ResourceType.LINK
                    resource.file = None
                    resource.external_url = sample["external_url"]

                resource.full_clean()
                resource.save()

                resource.targets.all().delete()

                for effect, selectors in sample["targets"]:
                    target = ResourceTarget(
                        resource=resource,
                        effect=effect,
                        **selectors,
                    )

                    target.full_clean()
                    target.save()

                self.stdout.write(
                    f"Seeded: {resource.title}"
                )

        self.stdout.write(
            self.style.SUCCESS(
                f"Resource seeding complete. "
                f"Created {created_count}, "
                f"updated {updated_count}."
            )
        )

    def write_sample_file(self, name, content):
        file_path = Path(
            private_resource_storage.path(name)
        )

        file_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        content_bytes = content.encode("utf-8")

        if (
            file_path.exists()
            and file_path.read_bytes() == content_bytes
        ):
            return

        file_path.write_bytes(content_bytes)
